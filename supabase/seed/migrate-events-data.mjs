#!/usr/bin/env node
/**
 * Generates supabase/seed/events-import.sql from js/events-data.js — the
 * site's current source of truth for events. Same rationale as
 * migrate-churches-data.mjs: load and evaluate the real file rather than
 * hand-transcribing it.
 *
 * Usage:
 *   node supabase/seed/migrate-events-data.mjs
 *
 * Output:
 *   supabase/seed/events-import.sql — review, then apply it.
 *
 * Ids are deterministic (UUIDv5 from each event's existing string id), so
 * re-running after an events-data.js update and re-applying is idempotent.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import vm from 'node:vm';
import { createHash } from 'node:crypto';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, '..', '..');
const sourcePath = join(repoRoot, 'js', 'events-data.js');
const outPath = join(__dirname, 'events-import.sql');

const source = readFileSync(sourcePath, 'utf8');
const sandbox = {};
vm.createContext(sandbox);
vm.runInContext(source + '\nthis.__NTX_EVENTS = NTX_EVENTS;', sandbox);
const NTX_EVENTS = sandbox.__NTX_EVENTS;

const NAMESPACE = 'a3f1c2d4-5b6e-4a7f-9c8d-1e2f3a4b5c6d'; // same fixed namespace as migrate-churches-data.mjs
function uuidv5(name, namespace = NAMESPACE) {
  const nsBytes = Buffer.from(namespace.replace(/-/g, ''), 'hex');
  const nameBytes = Buffer.from(name, 'utf8');
  const hash = createHash('sha1').update(Buffer.concat([nsBytes, nameBytes])).digest();
  hash[6] = (hash[6] & 0x0f) | 0x50;
  hash[8] = (hash[8] & 0x3f) | 0x80;
  const hex = hash.subarray(0, 16).toString('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20, 32)}`;
}

function sqlString(value) {
  if (value === null || value === undefined || value === '') return 'null';
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlBool(value) {
  return value ? 'true' : 'false';
}

const lines = [];
lines.push('-- Generated by supabase/seed/migrate-events-data.mjs — do not hand-edit.');
lines.push('-- Source: js/events-data.js');
lines.push('begin;');
lines.push('');
lines.push('-- Events --------------------------------------------------------------');

for (const e of NTX_EVENTS) {
  const id = uuidv5(`event:${e.id}`);
  const date = e.date ? `${sqlString(e.date)}::timestamptz` : 'null';
  const endDate = e.endDate ? `${sqlString(e.endDate)}::timestamptz` : 'null';
  lines.push(
    `insert into public.events ` +
    `(id, title, description, date, location, image_url, active, subtitle, host, date_text, end_date, event_time, address, link_url, link_text, tag, featured, orientation, notes) values ` +
    `(${sqlString(id)}, ${sqlString(e.title)}, ${sqlString(e.notes)}, ${date}, ${sqlString(e.location)}, ${sqlString(e.flyer)}, true, ` +
    `${sqlString(e.subtitle)}, ${sqlString(e.host)}, ${sqlString(e.dateText)}, ${endDate}, ${sqlString(e.time)}, ${sqlString(e.address)}, ` +
    `${sqlString(e.link)}, ${sqlString(e.linkText)}, ${sqlString(e.tag)}, ${sqlBool(e.featured)}, ${sqlString(e.orientation)}, ${sqlString(e.notes)}) ` +
    `on conflict (id) do update set title = excluded.title, date = excluded.date, location = excluded.location, ` +
    `image_url = excluded.image_url, subtitle = excluded.subtitle, host = excluded.host, date_text = excluded.date_text, ` +
    `end_date = excluded.end_date, event_time = excluded.event_time, address = excluded.address, link_url = excluded.link_url, ` +
    `link_text = excluded.link_text, tag = excluded.tag, featured = excluded.featured, orientation = excluded.orientation, notes = excluded.notes;`
  );
}

lines.push('');
lines.push('commit;');

writeFileSync(outPath, lines.join('\n') + '\n', 'utf8');
console.log(`Wrote ${outPath}`);
console.log(`  ${NTX_EVENTS.length} events processed.`);
